def is_technical_question(text: str) -> bool:
    """R1自身の本当の仕組みについての質問らしいか。事実集を付けるかどうかだけに使う。

    - Strata・LoRA・GitHub などシステム固有の語があれば、架空の話の中でも True
    - 仕組みの話題が R1 自身（あなた・R1・実際の…）を指していれば True
    - 架空の機械・模擬の作業だけの話（「この架空の機械はどうやって荷物を運ぶ？」）は False（創作に任せる）
    - 話題語だけで対象がはっきりしないときは、架空の語がなければ True（作り話を避ける側に倒す）
    """
    if not isinstance(text, str) or not text.strip():
        return False
    value = unicodedata.normalize("NFKC", text)
    if _SYSTEM.search(value):
        return True
    if not _TOPIC.search(value):
        return False
    if _SELF.search(value):
        # "Can you train me on this pretend machine?" の you は相手への依頼。架空の語があり、
        # 「実際の・本当に・R1」などの強い指し示しがなければ創作に任せる。
        if _FICTION.search(value) and not re.search(r"R1|アールワン|実際|本当|実機|\breal|\bactual|\br ?1\b|\byour (?:own|real)", value, re.I):
            return False
        return True
    return not _FICTION.search(value)
